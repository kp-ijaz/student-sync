using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using StudentSync.Application.Common;
using StudentSync.Domain.AI;
using StudentSync.Domain.Communication;
using StudentSync.Domain.Scheduling;

namespace StudentSync.Application.AI;

/// <summary>Executes queued AI jobs in the background. Safe to run more than once for the same job.</summary>
public sealed class AiJobRunner(IAppDbContext db, ITenantContext tenant, ILanguageModel llm, IClock clock, NotificationService notify, ILogger<AiJobRunner> logger)
{
    private const int MaxAttempts = 3;

    public const string SystemPrompt = """
        You turn a tuition class transcript into structured revision material for a teacher to review.
        Rules:
        - Use only information that is present in the transcript. Never invent formulas, homework, deadlines, examples or who said what.
        - Homework items must quote the exact transcript words as evidence and include a confidence between 0 and 1. Include a deadline only if one was explicitly stated.
        - practiceQuestions, flashcards and nextClassAgenda are your own suggestions; keep them relevant to the topics discussed.
        - Use the transcript timestamps (in seconds) for sources and timestamps where available.
        - Refer to learners as "a student"; never include personal names of students.
        - Respond with a single JSON object and nothing else, using exactly these camelCase keys:
          recap (string), learningOutcomes (string[]), topicNotes ({topic, notes, sources:[{startSeconds, quote}]}[]),
          definitions ({term, definition, formula, source:{startSeconds, quote}}[]), examples ({title, steps:string[], source}[]),
          questionsAnswered ({question, answer, askedBy, source}[]), unansweredQuestions (string[]),
          homework ({description, statedDeadline, confidence, evidence:{startSeconds, quote}}[]), revisionSummary (string),
          practiceQuestions ({type, question, options, answer, explanation}[]), flashcards ({front, back}[]),
          nextClassAgenda (string[]), timestamps ({startSeconds, label}[]).
          Use empty arrays when a section does not apply.
        """;

    public async Task RunLessonDraftAsync(Guid tenantId, Guid jobId, CancellationToken ct)
    {
        using var _ = tenant.BeginScope(tenantId);
        var job = await db.AiJobs.FirstOrDefaultAsync(j => j.Id == jobId, ct);
        if (job is null || job.Status is AiJobStatus.Succeeded or AiJobStatus.Failed or AiJobStatus.Blocked) return;

        job.Status = AiJobStatus.Running;
        job.StartedAtUtc = clock.UtcNow;
        await db.SaveChangesAsync(ct);

        if (!llm.IsConfigured)
        {
            await FailAsync(job, "No AI language-model provider is configured.", ct);
            return;
        }

        var transcript = await db.Transcripts.Include(t => t.Segments).FirstOrDefaultAsync(t => t.Id == job.TranscriptId, ct);
        var session = await db.Sessions.FirstOrDefaultAsync(s => s.Id == job.SessionId, ct);
        if (transcript is null || session is null)
        {
            await FailAsync(job, "The transcript or session no longer exists.", ct);
            return;
        }

        var names = await db.SessionParticipants.Where(p => p.SessionId == session.Id)
            .Select(p => p.Student!.User!.FullName).ToListAsync(ct);
        var prompt = BuildPrompt(session.Title, transcript, names);

        string? lastError = null;
        while (job.Attempts < MaxAttempts)
        {
            job.Attempts++;
            var result = await llm.CompleteAsync(SystemPrompt, prompt, 16000, ct);
            db.AiUsage.Add(new AiUsageRecord
            {
                JobId = job.Id,
                Feature = "lesson_draft",
                Provider = llm.ProviderName,
                Model = llm.ModelName,
                InputTokens = result.InputTokens,
                OutputTokens = result.OutputTokens,
                EstimatedCostUsd = result.EstimatedCostUsd,
            });
            if (result.Success && TryParse(result.Text, out var content, out lastError))
            {
                var json = JsonSerializer.Serialize(content, AiService.Json);
                var draft = new AiLessonDraft
                {
                    SessionId = session.Id,
                    TranscriptId = transcript.Id,
                    JobId = job.Id,
                    ContentJson = json,
                    Provider = llm.ProviderName,
                    Model = llm.ModelName,
                    Status = AiDraftStatus.AwaitingTeacherReview,
                };
                draft.Versions.Add(new AiLessonDraftVersion { VersionNumber = 1, ContentJson = json, ChangeNote = "Generated by AI" });
                db.AiDrafts.Add(draft);
                job.Status = AiJobStatus.Succeeded;
                job.DraftId = draft.Id;
                job.CompletedAtUtc = clock.UtcNow;
                job.FailureReason = null;
                await notify.NotifyAsync([session.TeacherId], NotificationType.AiDraftReady, $"AI draft ready to review: {session.Title}",
                    "Review, edit and approve before anything is shared with students.", $"/ai/drafts/{draft.Id}", $"ai-draft:{draft.Id}", ct);
                await db.SaveChangesAsync(ct);
                return;
            }
            lastError = result.Success ? lastError : result.Error;
            logger.LogWarning("AI lesson draft attempt {Attempt} failed for job {JobId}: {Error}", job.Attempts, job.Id, lastError);
            await db.SaveChangesAsync(ct);
            if (job.Attempts < MaxAttempts) await Task.Delay(TimeSpan.FromSeconds(Math.Pow(2, job.Attempts)), ct);
        }
        await FailAsync(job, $"AI processing failed after {MaxAttempts} attempts: {lastError}", ct);
    }

    private async Task FailAsync(AiProcessingJob job, string reason, CancellationToken ct)
    {
        job.Status = AiJobStatus.Failed;
        job.FailureReason = reason.Length > 1000 ? reason[..1000] : reason;
        job.CompletedAtUtc = clock.UtcNow;
        await db.SaveChangesAsync(ct);
    }

    /// <summary>Builds the user prompt with student names redacted (data minimisation).</summary>
    public static string BuildPrompt(string sessionTitle, Domain.Content.ClassTranscript transcript, IEnumerable<string> participantNames)
    {
        var tokens = participantNames.SelectMany(n => n.Split(' ', StringSplitOptions.RemoveEmptyEntries).Append(n))
            .Where(t => t.Length > 2).Distinct().OrderByDescending(t => t.Length).ToList();
        string Redact(string s) => tokens.Aggregate(s, (acc, t) => Regex.Replace(acc, $@"\b{Regex.Escape(t)}\b", "a student", RegexOptions.IgnoreCase));

        var sb = new StringBuilder();
        sb.AppendLine($"Class: {sessionTitle}").AppendLine("Transcript (start seconds | speaker | text):");
        foreach (var seg in transcript.Segments.OrderBy(s => s.Sequence))
            sb.AppendLine($"{seg.StartSeconds:0} | {Redact(seg.Speaker ?? "unknown")} | {Redact(seg.Text)}");
        return sb.ToString();
    }

    public static bool TryParse(string? text, out LessonDraftContent content, out string? error)
    {
        content = null!;
        error = null;
        if (string.IsNullOrWhiteSpace(text)) { error = "Empty response."; return false; }
        var start = text.IndexOf('{');
        var end = text.LastIndexOf('}');
        if (start < 0 || end <= start) { error = "The response did not contain JSON."; return false; }
        try
        {
            content = JsonSerializer.Deserialize<LessonDraftContent>(text[start..(end + 1)], AiService.Json)!;
        }
        catch (JsonException ex) { error = $"Invalid JSON: {ex.Message}"; return false; }
        if (content is null) { error = "Empty JSON."; return false; }
        var problems = content.Validate();
        if (problems.Count > 0) { error = string.Join(" ", problems); return false; }
        return true;
    }
}
